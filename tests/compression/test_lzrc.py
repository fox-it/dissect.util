@pytest.mark.parametrize(*PARAMS)
def test_lzrc_decompress(data: bytes, buflen: int, digest: str) -> None:
    assert hashlib.sha256(lzrc.decompress(data, buflen)).hexdigest() == digest
    assert hashlib.sha256(lzrc.decompress(data)).hexdigest() == digest


def test_lzrc_decompress_truncated() -> None:
    """Test whether a stream that ends prematurely raises an error."""
    with pytest.raises(ValueError, match="Truncated LZRC stream"):
        lzrc.decompress(BLOCK_0[:40], 32768)


def test_lzrc_decompress_exceeds_buffer() -> None:
    """Test whether a stream that is larger than the buffer raises an error."""
    with pytest.raises(ValueError, match="exceeds output buffer"):
        lzrc.decompress(BLOCK_0, 1024)


COMPRESS_PARAMS = (
    ("data",),
    [
        pytest.param(b"", id="empty"),
        pytest.param(b"Hello, Dissect!\n", id="literal"),
        pytest.param(b"\x00" * 32768, id="zeros"),
        pytest.param(bytes(range(256)) * 128, id="repeated"),
        pytest.param(b"ABCD" * 3 + b"E" + b"ABCD" * 300, id="long_match"),
        pytest.param(
            b"".join(hashlib.sha256(str(i).encode()).digest() for i in range(128)),
            id="incompressible",
        ),
    ],
)


@pytest.mark.parametrize(*COMPRESS_PARAMS)
def test_lzrc_compress(data: bytes) -> None:
    """Test whether compressing and decompressing data results in the original data."""
    assert lzrc.decompress(lzrc.compress(data), len(data)) == data
    assert lzrc.decompress(lzrc.compress(io.BytesIO(data)), len(data)) == data
    assert lzrc.decompress(lzrc.compress(data)) == data


def test_lzrc_compress_reduces_size() -> None:
    """Test whether compressing data that has a lot of matches results in a smaller stream."""
    data = bytes(range(256)) * 128
    assert len(lzrc.compress(data)) < len(data)


